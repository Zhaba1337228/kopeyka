import { test, expect } from '@playwright/test';
import path from 'node:path';

const input=process.env.KOPEYKA_TEST_CRITERIA;
test.skip(!input,'Generate tests/criteria_fixtures.py first');
test('review source, correct units and metadata, export and preserve parent',async({page})=>{
  test.setTimeout(120000);
  const errors=[];page.on('pageerror',e=>errors.push(e.message));
  await page.setViewportSize({width:1440,height:1000});
  await page.goto(process.env.KOPEYKA_TEST_URL||'http://127.0.0.1:8506');
  await page.getByLabel('Карточка КФЗ',{exact:true}).setInputFiles(path.join(input,'report.pdf'));
  await page.getByLabel('Подтверждающие документы',{exact:true}).setInputFiles(path.join(input,'review.docx'));
  const response=page.waitForResponse(r=>r.url().endsWith('/api/check')&&r.request().method()==='POST');
  await page.getByRole('button',{name:'Начать сверку'}).click();
  const first=await (await response).json();
  await page.getByRole('button',{name:/^Документы/}).click();
  await page.getByRole('button',{name:'review.docx',exact:true}).click();
  await expect(page.locator('.review-source')).toContainText('100,00');
  await page.getByLabel('Подтвердить сумму по выбранному фрагменту').check();
  await page.getByLabel('Сумма в исходном документе',{exact:true}).fill('100,00');
  await page.getByLabel('Единица измерения',{exact:true}).selectOption('1000');
  await page.getByText('Уточнить реквизиты',{exact:true}).click();
  await page.locator('.document-review').getByLabel('Договор',{exact:true}).fill('24/03/15-01');
  await page.getByLabel('Основание решения',{exact:true}).fill('Уточнены договор и единицы по оригиналу');
  await page.locator('.document-review').screenshot({path:'../outputs/criteria-manual-review.png'});
  await page.setViewportSize({width:390,height:844});
  expect(await page.evaluate(()=>document.documentElement.scrollWidth<=window.innerWidth)).toBe(true);
  await page.setViewportSize({width:1440,height:1000});
  await page.getByRole('button',{name:'Подтвердить и пересчитать'}).click();
  await expect(page.getByRole('heading',{name:'Что изменилось · версия 1 → 2'})).toBeVisible();
  await expect(page.locator('.review-conclusion')).toContainText('Суммы проверяемых статей согласуются');
  const download=page.waitForEvent('download');
  await page.getByRole('link',{name:'Скачать Excel'}).click();
  expect((await download).suggestedFilename()).toMatch(/\.xlsx$/);
  const old=await (await page.request.get(new URL(`/api/session/${first.session}`,page.url()).href)).json();
  expect(old.result.documents[0].amount).toBeNull();
  expect(old.result.rows).toEqual(first.result.rows);
  expect(errors).toEqual([]);
});

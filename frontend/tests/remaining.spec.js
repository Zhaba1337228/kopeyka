import {test, expect} from '@playwright/test';
import path from 'node:path';

const input=process.env.KOPEYKA_TEST_REMAINING;
test.skip(!input,'Generate tests/remaining_fixtures.py first');
test('formula provenance and independent detail comparison preserve the monetary total',async({page})=>{
  test.setTimeout(120000);
  const errors=[];page.on('pageerror',e=>errors.push(e.message));
  await page.goto(process.env.KOPEYKA_TEST_URL||'http://127.0.0.1:8509');
  await page.getByLabel('Карточка КФЗ',{exact:true}).setInputFiles(path.join(input,'report.pdf'));
  await page.getByLabel('Подтверждающие документы',{exact:true}).setInputFiles(path.join(input,'formula.xlsx'));
  const response=page.waitForResponse(r=>r.url().endsWith('/api/check')&&r.request().method()==='POST');
  await page.getByRole('button',{name:'Начать сверку'}).click();
  const first=await (await response).json();
  expect(first.result.total.confirmed).toBe('1200.00');
  expect(first.result.documents[0].document_date).toBe('2026-03-15');
  await page.getByRole('button',{name:/^Документы/}).click();
  await page.getByRole('button',{name:'formula.xlsx',exact:true}).click();
  await page.getByText('Как рассчитано значение ячейки',{exact:true}).click();
  await expect(page.locator('.review-source')).toContainText('=SUM(B7:B8)');
  await expect(page.locator('.review-source')).toContainText('B7: 1000');
  await page.getByRole('button',{name:'Результаты',exact:true}).click();
  await page.getByRole('tab',{name:'3. Добавить ответ'}).click();
  await page.getByLabel('Дополнительные документы',{exact:true}).setInputFiles(path.join(input,'details.docx'));
  const appended=page.waitForResponse(r=>r.url().endsWith('/documents')&&r.request().method()==='POST');
  await page.getByRole('button',{name:'Добавить и сравнить версии'}).click();
  const added=await appended;
  expect(added.ok()).toBe(true);
  const after=await added.json();
  expect(after.result.total.confirmed).toBe('1200.00');
  expect(after.result.indicators.every(m=>m.status==='Совпадает')).toBe(true);
  const old=await (await page.request.get(new URL(`/api/session/${first.session}`,page.url()).href)).json();
  expect(old.result.indicators.every(m=>m.status==='Недостаточно данных')).toBe(true);
  await page.getByText('Изменения детальных показателей',{exact:true}).click();
  await expect(page.locator('.comparison-docs')).toContainText('чел.-мес.');
  await expect(page.locator('.comparison-docs')).toContainText('Недостаточно данных');
  await expect(page.locator('.comparison-docs')).toContainText('Совпадает');
  await page.locator('.coverage > summary').click();
  const labor=page.locator('.coverage tbody tr').filter({hasText:'Трудоёмкость'});
  await labor.getByRole('button').filter({hasText:'details.docx'}).click();
  await expect(page.locator('.coverage .review-source')).toContainText('В чел.-мес.');
  await page.locator('.coverage').screenshot({path:'../outputs/remaining-details.png'});
  await page.setViewportSize({width:390,height:844});
  expect(await page.evaluate(()=>document.documentElement.scrollWidth<=innerWidth+1)).toBe(true);
  await page.screenshot({path:'../outputs/remaining-mobile.png',fullPage:true});
  expect(errors).toEqual([]);
});

test('correct a KFZ cell from its fragment without changing the original version',async({page})=>{
  test.setTimeout(120000);
  await page.goto(process.env.KOPEYKA_TEST_URL||'http://127.0.0.1:8509');
  await page.getByLabel('Карточка КФЗ',{exact:true}).setInputFiles(path.join(input,'ambiguous.pdf'));
  await page.getByLabel('Подтверждающие документы',{exact:true}).setInputFiles(path.join(input,'formula.xlsx'));
  const response=page.waitForResponse(r=>r.url().endsWith('/api/check')&&r.request().method()==='POST');
  await page.getByRole('button',{name:'Начать сверку'}).click();
  const first=await (await response).json();
  expect(first.result.rows[0].reported).toBeNull();
  await page.getByText('Проверить значение в КФЗ',{exact:true}).click();
  await expect(page.locator('.report-review img')).toBeVisible();
  await page.getByLabel('Значение в КФЗ',{exact:true}).fill('1200');
  await page.getByLabel('Основание исправления КФЗ',{exact:true}).fill('Значение сверено с фрагментом КФЗ');
  const recalculated=page.waitForResponse(r=>r.url().endsWith('/recalculate')&&r.request().method()==='POST');
  await page.getByRole('button',{name:'Подтвердить значение КФЗ'}).click();
  const after=await (await recalculated).json();
  expect(after.result.total.status).toBe('Совпадает');
  const proof=after.result.evidence[after.result.rows[0].report_evidence_id];
  expect(proof.manual).toBe(true);expect(proof.original_value).toBeNull();
  const old=await (await page.request.get(new URL(`/api/session/${first.session}`,page.url()).href)).json();
  expect(old.result.rows[0].reported).toBeNull();
  const repeated=await page.request.post(new URL(`/api/session/${after.session}/recalculate`,page.url()).href,{data:{}});
  expect(repeated.ok()).toBe(true);
  expect((await repeated.json()).result.total.status).toBe('Совпадает');
  const invalid=await page.request.post(new URL(`/api/session/${after.session}/recalculate`,page.url()).href,{data:{report_decision:{code:'0400',source:after.result.documents[0].evidence_ids[0],raw:'0',reason:'Чужой источник'}}});
  expect(invalid.status()).toBe(400);
  await page.getByText('Проверить значение в КФЗ',{exact:true}).click();
  await expect(page.locator('.report-review')).toContainText('Значение сверено с фрагментом КФЗ');
  await page.locator('.report-review').screenshot({path:'../outputs/remaining-report-review.png'});
});
